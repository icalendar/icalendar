# frozen_string_literal: true

require 'ice_cube'

module Icalendar

  class Timezone < Component
    module TzProperties
      def self.included(base)
        base.class_eval do
          required_property :dtstart, Icalendar::Values::DateTime
          required_property :tzoffsetfrom, Icalendar::Values::UtcOffset
          required_property :tzoffsetto, Icalendar::Values::UtcOffset

          optional_property :rrule, Icalendar::Values::Recur, true
          optional_property :comment
          optional_property :rdate, Icalendar::Values::DateTime
          optional_property :tzname

          transient_variable :@cached_occurrences
          transient_variable :@occurrences
        end
      end

      def occurrences
        @occurrences ||= IceCube::Schedule.new(dtstart.to_time) do |s|
          rrule.each do |rule|
            s.add_recurrence_rule floating_until(IceCube::Rule.from_ical(rule.value_ical))
          end
          rdate.each do |date|
            s.add_recurrence_time date.to_time
          end
        end.all_occurrences_enumerator
      end

      def previous_occurrence(from)
        from = IceCube::TimeUtil.match_zone(from, dtstart.to_time)

        @cached_occurrences ||= []
        while @cached_occurrences.empty? || @cached_occurrences.last <= from
          begin
            @cached_occurrences << occurrences.next
          rescue StopIteration
            break
          end
        end

        @cached_occurrences.reverse_each.find { |occurrence| occurrence < from }
      end

      private

      # An observance's DTSTART is a local time in TZOFFSETFROM, but is
      # evaluated here as a floating time. UNTIL is in UTC, so move it into the
      # same frame, or occurrences east of UTC would be cut off early.
      def floating_until(rule)
        return rule if rule.until_time.nil?
        offset = tzoffsetfrom.value
        seconds = offset.hours * 3600 + offset.minutes * 60 + offset.seconds
        seconds = -seconds if tzoffsetfrom.behind?
        rule.until(rule.until_time + seconds)
      end
    end
    class Daylight < Component
      include Marshable
      include TzProperties

      def initialize
        super 'daylight', 'DAYLIGHT'
      end
    end
    class Standard < Component
      include Marshable
      include TzProperties

      def initialize
        super 'standard', 'STANDARD'
      end
    end


    # Records the TZInfo zone and local date range a timezone was generated
    # for, so that timezones with the same TZID can be regenerated as one.
    TzinfoSource = Struct.new(:identifier, :first, :last, :dst, keyword_init: true)

    required_property :tzid

    optional_single_property :last_modified, Icalendar::Values::DateTime
    optional_single_property :tzurl, Icalendar::Values::Uri

    component :daylight, false, Icalendar::Timezone::Daylight
    component :standard, false, Icalendar::Timezone::Standard

    attr_accessor :tzinfo_source

    def initialize
      super 'timezone'
    end

    # Combine another timezone with the same TZID into this one.
    #
    # When both were generated by TZInfo for the same zone, the observances are
    # regenerated to cover every date either one was generated for. Otherwise
    # the other timezone's observances are added, skipping identical ones.
    def merge!(other)
      return self if other.equal?(self)

      if tzinfo_mergeable?(other)
        source = tzinfo_source
        first = [source.first, other.tzinfo_source.first].min
        last = [source.last, other.tzinfo_source.last].max
        return self if first == source.first && last == source.last

        rebuilt = TZInfo::Timezone.get(source.identifier).ical_timezone_for_range(first, last, source.dst)
        replace_observances rebuilt.daylights + rebuilt.standards
        self.tzinfo_source = rebuilt.tzinfo_source
      else
        existing = (daylights + standards).map(&:to_ical)
        (other.daylights + other.standards).each do |observance|
          add_component observance unless existing.include?(observance.to_ical)
        end
        self.tzinfo_source = nil
      end
      self
    end

    def valid?(strict = false)
      daylights.empty? && standards.empty? and return false
      daylights.all? { |d| d.valid? strict } or return false
      standards.all? { |s| s.valid? strict } or return false
      super
    end

    def offset_for_local(local)
      standard = standard_for local
      daylight = daylight_for local

      if standard.nil? && daylight.nil?
        "+00:00"
      elsif daylight.nil?
        standard.last.tzoffsetto
      elsif standard.nil?
        daylight.last.tzoffsetto
      else
        sdst = standard.first
        ddst = daylight.first
        if sdst > ddst
          standard.last.tzoffsetto
        else
          daylight.last.tzoffsetto
        end
      end
    end

    def standard_for(local)
      possible = standards.map do |std|
        prev = std.previous_occurrence(local.to_time)
        [prev, std] unless prev.nil?
      end.compact
      possible.sort_by(&:first).last
    end

    def daylight_for(local)
      possible = daylights.map do |day|
        prev = day.previous_occurrence(local.to_time)
        [prev, day] unless prev.nil?
      end.compact
      possible.sort_by(&:first).last
    end

    private

    def tzinfo_mergeable?(other)
      tzinfo_source && other.tzinfo_source &&
        tzinfo_source.identifier == other.tzinfo_source.identifier &&
        defined?(TZInfo::Timezone) && TZInfo::Timezone.method_defined?(:transitions_up_to)
    end

    def replace_observances(observances)
      daylights.clear
      standards.clear
      observances.each { |observance| add_component observance }
    end
  end
end
